#[allow(dead_code)]
mod helpers;

use {
    solana_keypair::Keypair,
    solana_message::{Message, VersionedMessage},
    solana_signer::Signer,
    solana_transaction::versioned::VersionedTransaction,
};

use helpers::{
    setup, setup_mint_and_extra_metas, create_ata, mint_tokens, build_transfer_with_hook_ix,
    initialize_rate_limit, build_transfer_via_mover_ix,
};

#[test]
fn test_rate_limit_is_per_owner() {
    let (mut svm, payer, program_id) = setup();
    let mint = Keypair::new();

    setup_mint_and_extra_metas(&mut svm, &payer, &mint, &program_id);

    // Second wallet
    let payer2 = Keypair::new();
    svm.airdrop(&payer2.pubkey(), 1_000_000_000).unwrap();

    // Only payer2 needs an explicit init; setup already did payer
    initialize_rate_limit(&mut svm, &payer2, &mint, &program_id);

    // payer's ATA and payer2's ATA (one each — reused for both directions)
    let payer_ata  = create_ata(&mut svm, &payer, &payer.pubkey(),  &mint.pubkey());
    let payer2_ata = create_ata(&mut svm, &payer, &payer2.pubkey(), &mint.pubkey());

    // Fund both source accounts
    mint_tokens(&mut svm, &payer, &mint.pubkey(), &payer_ata,  1_000_000);
    mint_tokens(&mut svm, &payer, &mint.pubkey(), &payer2_ata, 1_000_000);

    // Owner 1 (payer) sends 1,000,000 to payer2
    let ix1 = build_transfer_with_hook_ix(
        &payer_ata, &payer2_ata, &mint.pubkey(), &payer.pubkey(), &program_id, 1_000_000, 9,
    );
    let blockhash = svm.latest_blockhash();
    let msg = Message::new_with_blockhash(&[ix1], Some(&payer.pubkey()), &blockhash);
    let tx = VersionedTransaction::try_new(VersionedMessage::Legacy(msg), &[&payer]).unwrap();
    let res = svm.send_transaction(tx);
    assert!(res.is_ok(), "owner 1 should succeed: {:?}", res.err());

    // Owner 2 (payer2) sends 1,000,000 in the SAME hour — must ALSO succeed
    let ix2 = build_transfer_with_hook_ix(
        &payer2_ata, &payer_ata, &mint.pubkey(), &payer2.pubkey(), &program_id, 1_000_000, 9,
    );
    let blockhash = svm.latest_blockhash();
    let msg = Message::new_with_blockhash(&[ix2], Some(&payer2.pubkey()), &blockhash);
    let tx = VersionedTransaction::try_new(VersionedMessage::Legacy(msg), &[&payer2]).unwrap();
    let res = svm.send_transaction(tx);
    assert!(res.is_ok(), "owner 2 should succeed (per-owner limit): {:?}", res.err());
}

